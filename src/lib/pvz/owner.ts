// ЕДИНСТВЕННОЕ место, где назначается главный администратор бота.
//
// Кабинет, кнопки и обычные правки базы эту роль не выдают и не забирают.
// При каждом заходе в кабинет база подтягивается сюда:
//   • человек с этим юзернеймом становится главным администратором;
//   • прежний главный администратор опускается до руководителя.
//
// Как передать роль: замените юзернейм ниже (без @) и опубликуйте кабинет заново.
// Пока строка пустая, главного администратора нет. Тогда роли
// «Руководитель» и «Администратор» из кабинета назначить нельзя.

/** Юзернейм Telegram без @. Пустая строка = роль никому не выдана. */
export const BOT_OWNER_USERNAME = "iwannabenever";

/** Имя, которым человек появится в базе, если его ещё не добавляли вручную. */
export const BOT_OWNER_NAME = "Главный администратор";

export function configuredOwnerUsername(): string {
  const username = BOT_OWNER_USERNAME.trim().replace(/^@+/, "").toLowerCase();
  if (!/^[a-z][a-z0-9_]{4,31}$/.test(username)) return "";
  return username;
}
